export const DICTIONARIES: Record<Locale, Dict> = { fr, en, ln, sw };

/** Traduit une clé ; retombe sur le français puis sur la clé elle-même. */
export function translate(locale: Locale, key: string, vars?: Record<string, string | number>): string {
  const value = DICTIONARIES[locale]?.[key] ?? fr[key] ?? key;
  if (!vars) return value;
  return Object.entries(vars).reduce(
    (text, [name, replacement]) => text.replaceAll(`{${name}}`, String(replacement)),
    value,
  );
}

export type Translator = (key: string, vars?: Record<string, string | number>) => string;

export function createTranslator(locale: Locale): Translator {
  return (key, vars) => translate(locale, key, vars);
}

/** Indique la part de clés traduites (utilisé dans la page « À propos »). */
export function coverage(locale: Locale): number {
  const total = Object.keys(fr).length;
  const translated = Object.keys(DICTIONARIES[locale] ?? {}).length;
  return Math.round((translated / total) * 100);
}
